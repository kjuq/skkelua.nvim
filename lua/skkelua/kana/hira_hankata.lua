local M = {}

---@param input string
---@return string
function M.hira_to_hankata(input)
	local katakana = hira_kata.hira_to_kata(input)
	local result = {}
	for _, c in ipairs(util.chars(katakana)) do
		result[#result + 1] = hankata_table[c] or c
	end
	return table.concat(result)
end

return M
